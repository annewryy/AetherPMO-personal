const fs = require('fs');

const configuredUrl = process.env.SUPABASE_URL || process.env.VITE_SUPABASE_URL || process.env.NEXT_PUBLIC_SUPABASE_URL || process.env.REACT_APP_SUPABASE_URL || 'YOUR_SUPABASE_PROJECT_URL';
// Production safeguard: an old environment value swapped the letters "n" and "m" in the project ref.
// Normalize the one known typo; do not silently rewrite unrelated Supabase projects.
const badProjectHost = 'rhbyfzimvpkkuljmnfct.supabase.co';
const correctProjectHost = 'rhbyfzimvpkkuljnmfct.supabase.co';
const url = configuredUrl.replace(badProjectHost, correctProjectHost);
if (url !== configuredUrl) {
    console.warn('[build-config] Corrected mistyped Supabase project URL. Update SUPABASE_URL in Vercel environment settings as well.');
}
if (url.includes('YOUR_SUPABASE_PROJECT_URL')) {
    throw new Error('Supabase URL not configured in deployment environment');
}
const anonKey = process.env.SUPABASE_ANON_KEY || process.env.VITE_SUPABASE_ANON_KEY || process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY || process.env.NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY || process.env.REACT_APP_SUPABASE_ANON_KEY || 'YOUR_SUPABASE_ANON_KEY';

const configContent = `// Automatically generated by build-config.js during Vercel deployment
window.SUPABASE_CONFIG = {
    url: "${url}",
    anonKey: "${anonKey}"
};
`;

fs.writeFileSync('supabase-config.js', configContent);
console.log('supabase-config.js successfully generated.');

// ── 캐시버스팅: app.js 버전 파라미터를 커밋 해시(또는 타임스탬프)로 자동 갱신 ──
const buildVersion = process.env.VERCEL_GIT_COMMIT_SHA
    ? process.env.VERCEL_GIT_COMMIT_SHA.slice(0, 7)
    : Date.now().toString(36);

let html = fs.readFileSync('index.html', 'utf-8');
html = html.replace(/app\.js\?v=[^"']+/, `app.js?v=${buildVersion}`);
html = html.replace(/monthly-effort\.js(\?v=[^"']+)?/, `monthly-effort.js?v=${buildVersion}`);
fs.writeFileSync('index.html', html);
console.log(`app.js & monthly-effort.js cache-busting version updated to: ${buildVersion}`);

// ── sw.js 캐시 버전 갱신: 배포 시 서비스 워커 캐시 즉시 교체 ──
if (fs.existsSync('sw.js')) {
    let sw = fs.readFileSync('sw.js', 'utf-8');
    sw = sw.replace(/const CACHE_VERSION = '[^']+';/, `const CACHE_VERSION = 'aetherpmo-${buildVersion}';`);
    fs.writeFileSync('sw.js', sw);
    console.log(`sw.js CACHE_VERSION updated to: aetherpmo-${buildVersion}`);
}
